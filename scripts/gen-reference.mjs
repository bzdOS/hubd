/* ── markdown ── */
// Text from the code, made safe for a renderer: outside a code span `<name>` is an HTML tag and
// vanishes, and `*` starts emphasis.
const prose = (s) => String(s).split(/(`[^`]*`)/).map((p, i) => i % 2 ? p : p.replace(/</g, '&lt;').replace(/\*/g, '\\*')).join('');
// A table cell: one line, and `|` escaped even inside a code span, as GFM tables need.
const cell = (s) => prose(String(s ?? '').replace(/\s*\n\s*/g, ' ')).replace(/\|/g, '\\|');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const page = (title, ...blocks) => [MARKER, `# ${title}`, ...blocks].join('\n\n') + '\n';

/* ── running the code ── */
const hubEnv = (dir) => ({ PATH: process.env.PATH, HOME: dir, HUBD_DIR: dir, HUBD_TEAM_DIR: dir, HUBD_NODE: 'oak' });
function hub(dir, args, input = '') {
  const r = spawnSync(process.execPath, [CLI, ...args], { cwd: dir, env: hubEnv(dir), input, encoding: 'utf8', timeout: 30000 });
  return { code: r.status, out: r.stdout || '', err: r.stderr || '' };
}
function mcpLists(dir) {
  const req = [
    { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-03-26', capabilities: {}, clientInfo: { name: 'gen-reference', version: '0' } } },
    { jsonrpc: '2.0', method: 'notifications/initialized' },
    { jsonrpc: '2.0', id: 2, method: 'tools/list' },
    { jsonrpc: '2.0', id: 3, method: 'prompts/list' },
  ].map(m => JSON.stringify(m)).join('\n') + '\n';
  const r = spawnSync(process.execPath, [SERVER], { cwd: dir, env: hubEnv(dir), input: req, encoding: 'utf8', timeout: 30000 });
  const res = {};
  for (const l of (r.stdout || '').split('\n')) { try { const m = JSON.parse(l); if (m.id != null) res[m.id] = m.result; } catch {} }
  if (!res[1] || !res[2] || !res[3]) throw new Error('the MCP server did not answer initialize, tools/list and prompts/list:\n' + (r.stderr || '').slice(0, 2000));
  return { instructions: res[1].instructions || '', tools: res[2].tools, prompts: res[3].prompts };
}

/* ── CLI ── */
const helpName = (usage) => usage.split(/[\s|]/)[0];
// The rows of `hub help` as printHelp lays them out: a usage under 33 characters shares its line
// with what it does (column 35); a longer one has it on the next line, indented 35; the extra
// lines of a row are indented 4.
function parseHelp(text) {
  const lines = text.split('\n'), rows = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^ {4}\S/.test(l) && rows.length) { rows.at(-1).more.push(l.trim()); continue; }
    if (!/^ {2}\S/.test(l)) continue;
    if (/^ {35}\S/.test(lines[i + 1] || '')) rows.push({ usage: l.trim(), what: lines[++i].trim(), more: [] });
    else rows.push({ usage: l.slice(2, 35).trim(), what: l.slice(35).trim(), more: [] });
  }
  return rows;
}
const unparseHelp = (rows) => rows.map(({ usage, what, more }) =>
  [usage.length < 33 ? '  ' + usage.padEnd(33) + what : '  ' + usage + '\n' + ' '.repeat(35) + what, ...more.map(m => '    ' + m)].join('\n')).join('\n');

// command('name', …) and command(['name', 'alias'], …) in cli.mjs, one group per call.
const registered = () => [...src('hub/cli.mjs').matchAll(/^command\((\[[^\]]*\]|'[^']*')/gm)]
  .map(m => [...m[1].matchAll(/'([^']+)'/g)].map(x => x[1]));

function cliPage(helpText, problems) {
  const body = helpText.split('\n').slice(4).join('\n').replace(/\n+$/, '');
  const rows = parseHelp(body);
  if (unparseHelp(rows) !== body) problems.push('cli: `hub help` is not laid out the way parseHelp reads it; update parseHelp');
  for (const r of rows) if (r.usage.includes('`')) problems.push(`cli: a usage holds a backtick: ${r.usage}`);
  const cmds = new Map();
  for (const r of rows) { const n = helpName(r.usage); if (!cmds.has(n)) cmds.set(n, []); cmds.get(n).push(r); }
  const groups = registered();
  const aliases = new Map([...cmds.keys()].map(n => [n, []]));
  for (const g of groups) {
    const named = g.filter(n => cmds.has(n));
    for (const n of g) {
      if (n.startsWith('_') || cmds.has(n)) continue;
      if (named.length) aliases.get(named[0]).push(n);
      else problems.push(`cli: command "${n}" is registered but \`hub help\` has no line for it`);
    }
  }
  const known = new Set(groups.flat());
  for (const n of cmds.keys()) if (!known.has(n)) problems.push(`cli: \`hub help\` lists "${n}", which is not a registered command`);

  const index = [...cmds].map(([n, rs]) => [`[\`${n}\`](#${n})`, rs.map(r => r.what).join('; ')]);
  const sections = [...cmds].map(([n, rs]) => {
    const lines = [`## ${n}`, ''];
    for (const r of rs) {
      lines.push(`- \`hub ${r.usage}\` — ${prose(r.what)}`);
      for (const m of r.more) lines.push('', `  ${prose(m)}`);
    }
    const al = aliases.get(n).filter(a => !rs.some(r => r.usage.split(/[\s|]+/).includes(a)));
    if (al.length)lines.push('', 'Also: ' + al.map(a => `\`hub ${a}\``).join(', '));
    return lines.join('\n');
  });
  const flags = new Map();
  for (const [n, rs] of cmds) for (const r of rs) for (const m of r.usage.matchAll(/(?<![\w<-])(--?[a-zA-Z][\w-]*)/g)) {
    if (known.has(m[1])) continue;   // `--version`, `-v`: the command itself
    if (!flags.has(m[1])) flags.set(m[1], new Set());
    flags.get(m[1]).add(n);
  }
  const flagRows = [...flags].sort(([a], [b]) => a.replace(/^-+/, '').localeCompare(b.replace(/^-+/, '')) || a.localeCompare(b))
    .map(([f, ns]) => [`\`${f}\``, [...ns].map(n => `[${n}](#${n})`).join(', ')]);
  return page('CLI',
    'Every `hub` command as `hub help` lists it; `hub <command> --help` prints the lines of one. ' +
    'Where a command needs an author (`--by`, `--agent`, `--from`), `HUBD_AGENT` stands in for a flag ' +
    'left out ([Environment](env.md)). What the commands read and write is in [Files](files.md).',
    table(['Command', 'What it does'], index),
    ...sections,
    '## Flags\n\nThe commands each flag appears with, in their usage lines.',
    table(['Flag', 'Commands'], flagRows));
}

