export function build() {
  const problems = [];
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hubd-ref-'));
  try {
    const dir = path.join(tmp, 'hub');
    fs.mkdirSync(dir);
    const help = hub(dir, ['help']);
    if (help.code !== 0) problems.push('cli: `hub help` exited ' + help.code);
    const mcp = mcpLists(dir);
    const pages = {
      'README.md': indexPage(),
      'cli.md': cliPage(help.out, problems),
      'mcp.md': mcpPage(mcp, problems),
      'env.md': envPage(problems),
      'files.md': filesPage(tmp, problems),
      'report.md': reportPage(tmp, mcp, problems),
      'prompts.md': promptsPage(mcp, problems),
    };
    // A page must read the same on every machine: no temp path, no home, no host name in it.
    for (const [name, text] of Object.entries(pages))
      for (const leak of [tmp, fs.realpathSync(tmp), os.homedir(), os.hostname()].filter(s => s && s.length > 3))
        if (text.includes(leak)) problems.push(`${name}: holds ${leak}, which differs from machine to machine`);
    return { pages, problems };
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { pages, problems } = build();
  for (const p of problems) console.error('problem: ' + p);
  let stale = 0;
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, want] of Object.entries(pages)) {
    let have = null;
    try { have = fs.readFileSync(path.join(OUT, name), 'utf8'); } catch {}
    if (have === want) continue;
    stale++;
    if (check) { console.error(`stale page: docs/reference/${name}`); continue; }
    fs.writeFileSync(path.join(OUT, name), want, 'utf8');
    console.log(`wrote docs/reference/${name}`);
  }
  for (const f of fs.readdirSync(OUT).filter(f => f.endsWith('.md') && !pages[f])) {
    stale++;
    console.error(`docs/reference/${f} is not generated; remove it or generate it`);
  }
  if (check && (stale || problems.length)) {
    console.error(`${stale} stale page(s), ${problems.length} problem(s) - run: node scripts/gen-reference.mjs`);
    process.exit(1);
  }
  if (problems.length) process.exit(1);
  console.log(check ? 'reference current' : (stale ? `${stale} page(s) written` : 'nothing to do - the reference is current'));
}
