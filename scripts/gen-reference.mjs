// Every file the package ships that runs, as package.json "files" lists them.
function shippedCode() {
  const out = [];
  const walk = (rel) => {
    const full = path.join(ROOT, rel);
    if (!fs.existsSync(full)) return;
    if (fs.statSync(full).isDirectory()) { for (const f of fs.readdirSync(full).sort()) walk(path.join(rel, f)); return; }
    if (/\.(mjs|js|sh)$/.test(rel)) out.push(rel);
  };
  for (const f of JSON.parse(src('package.json')).files) walk(f.replace(/\/$/, ''));
  return out;
}

function envPage(problems) {
  const used = new Set();
  for (const f of shippedCode()) for (const m of src(f).matchAll(/(?<![A-Z_])(HUBD_[A-Z0-9_]+|PROJECT_HUB_DIR)\b/g)) used.add(m[1]);
  const listed = ENV.flatMap(([, rows]) => rows.map(r => r[0]));
  for (const v of used) if (!listed.includes(v)) problems.push(`env: the code reads ${v}; add it to ENV`);
  for (const v of listed) if (!used.has(v)) problems.push(`env: ENV lists ${v}, which no shipped code reads`);
  return page('Environment',
    'Every variable hubd reads, from the code the package ships. Set them in the environment of the ' +
    'process: the MCP client\'s server entry (`--env NAME=value`), the shell, the unit that runs mesh-sync.',
    ...ENV.flatMap(([title, rows]) => [`## ${title}`, table(['Variable', 'Default', 'What it does'], rows.map(([n, d, w]) => [`\`${n}\``, d || '—', w]))]));
}

