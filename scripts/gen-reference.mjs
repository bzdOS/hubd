const SCHEMA_KEYS = new Set(['type', 'description', 'enum', 'items', 'properties', 'required', 'additionalProperties']);

function typeOf(v) {
  if (!v) return 'any';
  if (v.enum) return 'one of ' + v.enum.map(x => '`' + x + '`').join(', ');
  const t = Array.isArray(v.type) ? v.type.join(' or ') : v.type;
  if (t === 'array') { const it = typeOf(v.items); return (/\s/.test(it) ? '(' + it + ')' : it) + '[]'; }
  if (t === 'object' && v.additionalProperties) return 'object of ' + typeOf(v.additionalProperties);
  return t || 'any';
}
function paramRows(tool, props = {}, required = [], prefix = '', problems) {
  const rows = [];
  for (const [k, v] of Object.entries(props)) {
    const name = prefix + k;
    for (const key of Object.keys(v)) if (!SCHEMA_KEYS.has(key)) problems.push(`mcp: ${tool}.${name} has schema key "${key}", which the page does not show`);
    rows.push([`\`${name}\``, typeOf(v), required.includes(k) ? 'yes' : '', v.description || '']);
    if (v.properties) rows.push(...paramRows(tool, v.properties, v.required || [], name + '.', problems));
    if (v.items && v.items.properties) rows.push(...paramRows(tool, v.items.properties, v.items.required || [], name + '[].', problems));
  }
  return rows;
}

function mcpPage({ instructions, tools, prompts }, problems) {
  const byName = new Map(tools.map(t => [t.name, t]));
  const grouped = TOOL_GROUPS.flatMap(([, ns]) => ns);
  for (const n of grouped) if (!byName.has(n)) problems.push(`mcp: TOOL_GROUPS names ${n}, which the server does not offer`);
  for (const n of byName.keys()) if (grouped.filter(g => g === n).length !== 1) problems.push(`mcp: ${n} is in ${grouped.filter(g => g === n).length} groups of TOOL_GROUPS; put it in one`);
  const m = src('hub/index.mjs').match(/LOCAL_ONLY_TOOLS = new Set\(\[([^\]]*)\]\)/);
  const local = new Set(m ? [...m[1].matchAll(/'([^']+)'/g)].map(x => x[1]) : []);
  if (!local.size) problems.push('mcp: LOCAL_ONLY_TOOLS not found in hub/index.mjs');
  for (const n of local) if (!byName.has(n)) problems.push(`mcp: LOCAL_ONLY_TOOLS names ${n}, which the server does not offer`);

  const sections = TOOL_GROUPS.map(([title, ns]) => [`## ${title}`, ...ns.filter(n => byName.has(n)).map(n => {
    const t = byName.get(n), s = t.inputSchema || {};
    const rows = paramRows(n, s.properties, s.required || [], '', problems);
    return [`### ${n}`, prose(t.description),
      ...(local.has(n) ? ['Local only: not offered over HTTP.'] : []),
      rows.length ? table(['Parameter', 'Type', 'Required', 'Description'], rows) : 'No parameters.'].join('\n\n');
  })].join('\n\n'));
  const promptRows = prompts.map(p => [`\`${p.name}\``, p.arguments && p.arguments.length ? `${p.arguments.length}, all required ([which](prompts.md#variables))` : 'none', p.description || '']);
  return page('MCP tools',
    `What the MCP server, \`hubd\`, offers a client: ${tools.length} tools, ${prompts.length} prompts, and the ` +
    'instructions it sends when a client connects. A tool\'s description is what the client\'s model reads, ' +
    'word for word. A parameter under another (`reflect.goal`, `replace[].from`) is a field of that object, ' +
    'and "yes" under Required means required whenever the object is given.',
    'Over HTTP (`hubd --http`, [Self-hosting](../self-hosting.md)) every tool is offered but the local-only ' +
    'ones, and `HUBD_AGENT` fills no author: each call names its own ([Environment](env.md)).',
    '## At connect', '```text\n' + instructions + '\n```',
    '## Tools', table(['Group', 'Tools'], TOOL_GROUPS.map(([title, ns]) => [title, ns.map(n => `[${n}](#${n})`).join(' · ')])),
    ...sections,
    '## Prompts', 'A client inserts these into a conversation (`prompts/list`, `prompts/get`). `hub harvest` and ' +
    '`hub prompts render` print the same text.',
    table(['Prompt', 'Arguments', 'What it is'], promptRows));
}

