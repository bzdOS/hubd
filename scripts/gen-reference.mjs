// gen-reference.mjs — docs/reference/, generated from the code.
//
// A reference kept by hand describes the release it was written for: a flag
// lands, a tool gains a field, and the page goes on teaching the one before.
// These pages are built from what the code says of itself (`hub help`, the MCP
// server's tools/list and prompts/list, the report prefixes, the reflection's
// lists, the role templates) and from a few tables kept here: environment
// variables, hub files, tool groups, report routes. Each table is checked
// against the code: a variable, a tool or a prefix it misses fails the check,
// and so does a row for one that is gone; a file a hub holds that no row
// describes fails it too (the check builds a demo hub and walks it).
//
//   node scripts/gen-reference.mjs          # rewrite stale pages
//   node scripts/gen-reference.mjs --check  # exit 1 if a page is stale or a table misses something (gate)
